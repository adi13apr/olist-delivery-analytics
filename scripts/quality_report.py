"""Run the data-quality checks against olist.duckdb and write DATA_QUALITY.md.

Usage:
    python scripts/quality_report.py [--db olist.duckdb] [--out DATA_QUALITY.md]
"""

import argparse
import sys
from pathlib import Path

import duckdb

from checks import CHECKS, run_checks
from load import TABLES

ROOT = Path(__file__).resolve().parents[1]


def md_table(header, rows):
    lines = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    lines += ["| " + " | ".join(str(v) for v in row) + " |" for row in rows]
    return "\n".join(lines)


def check_rows(checks, results):
    return [
        (f"`{c.id}`", c.title, f"{results[c.id]:,}", c.unit, c.decision)
        for c in checks
    ]


def build_report(con):
    results = run_checks(con)
    row_counts = [
        (f"`{t}`", f"{con.execute(f'SELECT count(*) FROM {t}').fetchone()[0]:,}")
        for t in TABLES
    ]
    exclusions = con.execute(
        "SELECT exclusion_reason, orders FROM stg_delivery_exclusions ORDER BY sort_order"
    ).fetchall()
    rec = con.execute(
        "SELECT raw_order_rows, eligible_orders, excluded_orders, is_balanced FROM v_delivery_reconciliation"
    ).fetchone()
    raw_rows, eligible, excluded, balanced = rec

    header = ("Check", "Description", "Count", "Unit", "Decision")
    parts = [
        "# Data quality",
        "",
        "Generated by `scripts/quality_report.py` from the full Olist dataset. "
        "Do not edit by hand; rerun the script after reloading the data.",
        "",
        "Each check is a SQL file in [`sql/checks/`](sql/checks/). The same SQL runs in "
        "`tests/test_quality.py` against a synthetic fixture that plants at least one bad "
        "row for every check. Descriptions and decisions live in `scripts/checks.py`.",
        "",
        "## Raw row counts",
        "",
        md_table(("Table", "Rows"), row_counts),
        "",
        "## Required checks",
        "",
        md_table(header, check_rows([c for c in CHECKS if c.required], results)),
        "",
        "## Other findings",
        "",
        "Issues found while profiling the data that the brief did not list.",
        "",
        md_table(header, check_rows([c for c in CHECKS if not c.required], results)),
        "",
        "## Delivery metric exclusions",
        "",
        "Delivery metrics (`delivery_days`, `estimated_days`, `is_late` in `stg_orders`) use "
        "only delivered orders with valid dates. Every other order stays in `stg_orders` "
        "with exactly one `exclusion_reason`; the first matching rule below wins.",
        "",
        md_table(("Reason", "Orders"), [(f"`{r}`", f"{n:,}") for r, n in exclusions]),
        "",
        md_table(
            ("Raw order rows", "Eligible", "Excluded", "Balanced"),
            [(f"{raw_rows:,}", f"{eligible:,}", f"{excluded:,}", "yes" if balanced else "**NO**")],
        ),
        "",
    ]
    return "\n".join(parts)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--db", default=ROOT / "olist.duckdb", type=Path)
    parser.add_argument("--out", default=ROOT / "DATA_QUALITY.md", type=Path)
    args = parser.parse_args(argv)

    if not args.db.exists():
        print(f"{args.db} not found; run scripts/load.py first.", file=sys.stderr)
        return 1
    with duckdb.connect(str(args.db), read_only=True) as con:
        report = build_report(con)
    args.out.write_text(report, encoding="utf-8", newline="\n")
    print(f"Wrote {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
